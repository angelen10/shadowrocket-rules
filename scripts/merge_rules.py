"""Expand repository-owned rule sets without fetching remote dependencies."""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
BASE = "https://raw.githubusercontent.com/angelen10/shadowrocket-rules/refs/heads/main/"
SOURCE = ROOT / "sr_top500_banlist_ad.conf"
OUTPUT = ROOT / "sr_top500_banlist_ad_merged.conf"


def expand_rules(path: Path, policy: str) -> list[str]:
    result = [f"# BEGIN {path.name}"]
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        rule = line.strip()
        if not rule or rule.startswith("#"):
            result.append(line)
            continue
        fields = [field.strip() for field in rule.split(",")]
        supported = {"DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-KEYWORD", "DOMAIN-WILDCARD", "IP-CIDR", "IP-CIDR6", "USER-AGENT"}
        if fields[0] not in supported or len(fields) not in (2, 3) or not fields[1]:
            raise ValueError(f"{path.name}:{number}: unsupported rule: {rule}")
        if len(fields) == 3 and not (
            fields[0] in {"IP-CIDR", "IP-CIDR6"} and fields[2] == "no-resolve"
        ):
            raise ValueError(f"{path.name}:{number}: unsupported options: {rule}")
        result.append(",".join(fields[:2] + [policy] + fields[2:]))
    result.append(f"# END {path.name}")
    return result


def main() -> None:
    result = ["# Generated by scripts/merge_rules.py; edit the source conf/list files instead."]
    section = ""
    expanded = 0
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            section = stripped
        if section == "[General]" and stripped.partition("=")[0].strip() == "update-url":
            result.append(f"update-url = {BASE}{OUTPUT.name}")
            continue
        parts = [part.strip() for part in stripped.split(",")]
        if section == "[Rule]" and len(parts) >= 2 and parts[0] == "RULE-SET" and parts[1].startswith(BASE + "rule_set_"):
            filename = parts[1][len(BASE):]
            if len(parts) != 3 or "/" in filename or not filename.endswith(".list") or parts[2] not in {"REJECT", "DIRECT", "PROXY"}:
                raise ValueError(f"Unsupported local rule-set reference: {line}")
            result.extend(expand_rules(ROOT / filename, parts[2]))
            expanded += 1
        else:
            result.append(line)
    OUTPUT.write_text("\n".join(result) + "\n", encoding="utf-8")
    print(f"Generated {OUTPUT.name}: expanded {expanded} local rule sets")


if __name__ == "__main__":
    main()
