"""Build sr_merged.conf. Does not modify sr_source.conf or the banlist files."""

from pathlib import Path
from typing import Optional


ROOT = Path(__file__).resolve().parents[1]
BASE = "https://raw.githubusercontent.com/angelen10/shadowrocket-rules/refs/heads/main/"
SOURCE = ROOT / "sr_source.conf"
OUTPUT = ROOT / "sr_merged.conf"
POLICIES = {"REJECT", "DIRECT", "PROXY"}
DOMAIN_SETS = {
    "domain_set_reject.list",
    "domain_set_direct.list",
    "domain_set_proxy.list",
}
KEYWORD_LISTS = {"domain_keyword_proxy.list": "PROXY"}


def expand_rules(path: Path, policy: str) -> list[str]:
    result = [f"# BEGIN {path.name}"]
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        rule = line.strip()
        if not rule or rule.startswith("#"):
            result.append(line)
            continue
        fields = [field.strip() for field in rule.split(",")]
        supported = {"DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-KEYWORD", "DOMAIN-WILDCARD", "IP-CIDR", "IP-CIDR6", "USER-AGENT"}
        if fields[0] not in supported or len(fields) not in (2, 3) or not fields[1]:
            raise ValueError(f"{path.name}:{number}: unsupported rule: {rule}")
        if len(fields) == 3 and not (
            fields[0] in {"IP-CIDR", "IP-CIDR6"} and fields[2] == "no-resolve"
        ):
            raise ValueError(f"{path.name}:{number}: unsupported options: {rule}")
        result.append(",".join(fields[:2] + [policy] + fields[2:]))
    result.append(f"# END {path.name}")
    return result


def expand_domains(path: Path, policy: str) -> list[str]:
    result = [f"# BEGIN {path.name}"]
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        domain = line.strip()
        if not domain or domain.startswith("#"):
            result.append(line)
            continue
        if (
            not domain.startswith(".")
            or domain == "."
            or any(char in domain for char in " ,/\\*")
        ):
            raise ValueError(f"{path.name}:{number}: unsupported domain: {line}")
        result.append(f"DOMAIN-SUFFIX,{domain[1:]},{policy}")
    result.append(f"# END {path.name}")
    return result


def expand_keywords(path: Path, policy: str) -> list[str]:
    result = [f"# BEGIN {path.name}"]
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        keyword = line.strip()
        if not keyword or keyword.startswith("#"):
            result.append(line)
            continue
        if any(char in keyword for char in " ,/\\*"):
            raise ValueError(f"{path.name}:{number}: unsupported keyword: {line}")
        result.append(f"DOMAIN-KEYWORD,{keyword},{policy}")
    result.append(f"# END {path.name}")
    return result


def local_list_name(parts: list[str], kind: str) -> Optional[str]:
    if len(parts) < 2 or parts[0] != kind or not parts[1].startswith(BASE):
        return None
    return parts[1][len(BASE):]


def main() -> None:
    result = ["# Generated by scripts/merge_rules.py; edit the source conf/list files instead."]
    section = ""
    expanded_rules = 0
    expanded_domains = 0
    expanded_keywords = 0
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            section = stripped
        if section == "[General]" and stripped.partition("=")[0].strip() == "update-url":
            result.append(f"update-url = {BASE}{OUTPUT.name}")
            continue
        parts = [part.strip() for part in stripped.split(",")]
        rule_name = local_list_name(parts, "RULE-SET") if section == "[Rule]" else None
        domain_name = local_list_name(parts, "DOMAIN-SET") if section == "[Rule]" else None
        if rule_name in KEYWORD_LISTS:
            if len(parts) != 3 or parts[2] != KEYWORD_LISTS[rule_name]:
                raise ValueError(f"Unsupported keyword-list reference: {line}")
            result.extend(expand_keywords(ROOT / rule_name, parts[2]))
            expanded_keywords += 1
        elif rule_name is not None and rule_name.startswith("rule_set_"):
            if len(parts) != 3 or "/" in rule_name or not rule_name.endswith(".list") or parts[2] not in POLICIES:
                raise ValueError(f"Unsupported local rule-set reference: {line}")
            result.extend(expand_rules(ROOT / rule_name, parts[2]))
            expanded_rules += 1
        elif domain_name in DOMAIN_SETS:
            if len(parts) != 3 or parts[2] not in POLICIES:
                raise ValueError(f"Unsupported local domain-set reference: {line}")
            result.extend(expand_domains(ROOT / domain_name, parts[2]))
            expanded_domains += 1
        else:
            result.append(line)
    OUTPUT.write_text("\n".join(result) + "\n", encoding="utf-8")
    print(
        f"Generated {OUTPUT.name}: expanded {expanded_rules} local rule sets, "
        f"{expanded_domains} domain sets, and {expanded_keywords} keyword lists"
    )


if __name__ == "__main__":
    main()
